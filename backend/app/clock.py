"""时间来源的单一入口。

**为什么全部用服务器本地时间，而不是 UTC**：这是一个单机部署的校内系统，
使用者是中文教师和学生，所有时间都直接显示在界面上。

如果库里存 UTC、前端直显，教师看到的每个时间都会差 8 小时——晚上 8 点上传的作业
显示成中午 12 点，按时间排序的提交列表也是乱的。要修就得前端逐处转换，
漏一处就是一个说不清的 bug。而跨时区、跨夏令时的收益在这里是**零**：
只有一台服务器，只有一群人，全在同一时区。

所以：**库里存本地时间，前端直显，不做任何转换。**

另外，`datetime.utcnow()` 在 Python 3.12 起已废弃（本机跑的是 3.13）。
它还有一个更隐蔽的问题：返回的是 naive 对象，但语义是 UTC——
一旦有人拿它和 `datetime.now()` 相减，就会得到差 8 小时的结果且不报错。
统一走 `now()` 可以从源头杜绝这类混淆。
"""

from __future__ import annotations

from datetime import datetime


def now() -> datetime:
    """当前服务器本地时间（naive）。

    返回 naive 对象是刻意的：这个系统里所有时间都是同一时区的本地时间，
    引入 tzinfo 只会让 SQLite 的读写和比较多出一层无收益的复杂度。
    """
    return datetime.now()
